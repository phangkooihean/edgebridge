use crate::models::{AppState, DisplayLayout, KVM_PORT, WEB_PORT};
#[cfg(unix)]
use std::os::unix::fs::PermissionsExt;
use std::path::PathBuf;

pub fn config_dir_path() -> PathBuf {
    if let Ok(appdata) = std::env::var("APPDATA") {
        if !appdata.trim().is_empty() { return PathBuf::from(appdata).join("edgebridge"); }
    }
    let home = std::env::var("HOME").or_else(|_| std::env::var("USERPROFILE")).unwrap_or_else(|_| ".".into());
    PathBuf::from(home).join(".config/edgebridge")
}

/// Formats a display topology into a concise human-readable summary.
///
/// ```
/// use edgebridge::models::DisplayLayout;
/// use edgebridge::scripts::format_display_summary;
/// let s = format_display_summary(&DisplayLayout::default());
/// assert!(s.contains("Single [virtual 1920x1080]"));
/// ```
pub fn format_display_summary(dl: &DisplayLayout) -> String {
    let parts: Vec<String> = dl.monitors.iter().enumerate().map(|(i, m)| {
        let star = if m.is_primary { "*" } else { "" };
        format!("#{}{i1} {} ({}x{} @ {:.0}% -> {}x{} logical, {:.0}Hz, {}, pos {},{})",
            i + 1, star, m.connector, m.physical_width, m.physical_height,
            m.scale * 100.0, m.logical_width, m.logical_height, m.refresh_rate, m.orientation, m.x, m.y,
            i1 = ""
        )
    }).collect();
    format!("{} [virtual {}x{}]: {}", dl.display_mode, dl.total_logical_width, dl.total_logical_height, parts.join(" | "))
}

pub fn generate_lan_mouse_toml(state: &AppState) -> String {
    let mut fps = Vec::new();
    let mut clients = Vec::new();

    if state.peers.is_empty() {
        if let Some(p) = &state.active_peer {
            clients.push((p.hostname.clone(), p.ip.clone(), p.fingerprint.clone(), state.edge.as_str().to_string()));
        }
    } else {
        for (ip, p) in &state.peers {
            clients.push((p.hostname.clone(), ip.clone(), p.fingerprint.clone(), p.edge.as_str().to_string()));
        }
    }

    if clients.is_empty() {
        clients.push(("unpaired-peer".into(), "127.0.0.1".into(), None, state.edge.as_str().to_string()));
    }

    let mut client_blocks = String::new();
    for (peer_host, peer_ip, peer_fp, edge_str) in clients {
        if let Some(fp) = peer_fp.as_deref().filter(|s| !s.is_empty()) {
            fps.push(format!("\"{}\" = \"{}\"", fp, peer_host));
        }
        let enter_hook = format!(
            "curl -fsS -X POST http://127.0.0.1:{}/api/hook/enter -H 'Content-Type: application/json' -d '{{\"peer_ip\":\"{}\",\"peer_hostname\":\"{}\"}}' || true",
            WEB_PORT, peer_ip, peer_host
        );
        let leave_hook = format!(
            "curl -fsS -X POST http://127.0.0.1:{}/api/hook/leave -H 'Content-Type: application/json' -d '{{\"peer_ip\":\"{}\",\"peer_hostname\":\"{}\"}}' || true",
            WEB_PORT, peer_ip, peer_host
        );
        client_blocks.push_str(&format!(
            "\n[[clients]]\nposition = \"{}\"\nhostname = \"{}\"\nips = [\"{}\"]\nport = {}\nactivate_on_startup = true\nenter_hook = \"{}\"\nleave_hook = \"{}\"\n",
            edge_str, peer_host, peer_ip, KVM_PORT, enter_hook.replace('"', "\\\""), leave_hook.replace('"', "\\\"")
        ));
    }

    let fp_section = if fps.is_empty() { "# Waiting for peer TLS fingerprint".into() } else { fps.join("\n") };
    format!(
        "# Generated by EdgeBridge v1.0.0-rc.1 ({}) for {} ({})\nport = {}\nrelease_bind = [ \"KeyA\", \"KeyS\", \"KeyD\", \"KeyF\" ]\n\n[authorized_fingerprints]\n{}\n{}",
        state.role.label(), state.hostname, state.ip, KVM_PORT, fp_section, client_blocks
    )
}

pub fn write_config_files(state: &AppState) -> Result<String, String> {
    let dir = config_dir_path();
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    let toml = generate_lan_mouse_toml(state);
    std::fs::write(dir.join("lan-mouse.config.toml"), &toml).map_err(|e| e.to_string())?;

    #[cfg(target_os = "windows")]
    {
        let ps_path = dir.join("setup-firewall.ps1");
        let ps = format!(
            "New-NetFirewallRule -DisplayName 'EdgeBridge Web/Probe TCP' -Direction Inbound -Protocol TCP -LocalPort {} -Action Allow -ErrorAction SilentlyContinue\nNew-NetFirewallRule -DisplayName 'EdgeBridge KVM UDP' -Direction Inbound -Protocol UDP -LocalPort {} -Action Allow -ErrorAction SilentlyContinue\n",
            WEB_PORT, KVM_PORT
        );
        let _ = std::fs::write(&ps_path, ps);
    }

    #[cfg(unix)]
    {
        let fw_path = dir.join("setup-firewall-and-reclaim.sh");
        let sh = format!(
            "#!/usr/bin/env bash\nset -euo pipefail\nif command -v ufw >/dev/null 2>&1; then\n  sudo ufw allow {}/tcp || true\n  sudo ufw allow {}/udp || true\nfi\ngetent group input >/dev/null 2>&1 && sudo usermod -aG input \"$USER\" || true\n",
            WEB_PORT, KVM_PORT
        );
        let _ = std::fs::write(&fw_path, sh);
        if let Ok(meta) = std::fs::metadata(&fw_path) {
            let mut perms = meta.permissions();
            perms.set_mode(0o755);
            let _ = std::fs::set_permissions(&fw_path, perms);
        }
    }
    Ok(toml)
}
